a = float(input("Enter your first number: "))
b = float(input("Enter your second number: "))

sum_val = int(a + b) #type casting
sub = a - b
multiplication = a * b
divide = a / b
divisor = a % b
power = a ** b

print("Sum value is: ", sum_val)
print("Subtraction value is: ", sub)
print("Multiplication value is: ", multiplication)
print("Division value is: ", divide)
print("Remainder (modulus) value is: ", divisor)
print("Power value is: ", power)